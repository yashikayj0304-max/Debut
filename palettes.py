"""Vibes: palettes of two major colours (+ a small accent). Every family comes in a Rich and a Soft tone, and every palette
has its own light-mode and dark-mode values. The CSS is generated by build_css() into static/pop.css (see tools in tests)."""

# (key, label, primary, secondary, accent, tone)
FAMILIES = [
    ("grape", "Grape", "#5b3cc4", "#c026d3", "#f0abfc", "#8b6fe0", "#f0abfc", "#ddd6fe"),
    ("ocean", "Ocean", "#0b5fa5", "#0891b2", "#67e8f9", "#3b8ee0", "#7dd3fc", "#bae6fd"),
    ("forest", "Forest", "#166534", "#0f766e", "#bef264", "#3da56a", "#86efac", "#bbf7d0"),
    ("sunset", "Sunset", "#c2410c", "#be185d", "#fbbf24", "#f07a4a", "#fdba74", "#fde68a"),
    ("berry", "Berry", "#9d174d", "#6d28d9", "#f9a8d4", "#e0568d", "#c4b5fd", "#fbcfe8"),
    ("midnight", "Midnight", "#1e3a8a", "#4f46e5", "#38bdf8", "#6677d9", "#a5b4fc", "#c7d2fe"),
    ("mango", "Mango", "#b45309", "#dc2626", "#fde047", "#eba02c", "#fde047", "#fef3c7"),
    ("mint", "Mint", "#0f766e", "#0369a1", "#5eead4", "#35b6a3", "#99f6e4", "#ccfbf1"),
    ("cocoa", "Cocoa", "#6b3f26", "#a16207", "#fcd34d", "#a47a5c", "#e7c9a9", "#f5e6d3"),
    ("slate", "Slate", "#334155", "#6366f1", "#cbd5e1", "#7487a3", "#cbd5e1", "#e2e8f0"),
    ("coral", "Coral", "#be123c", "#ea580c", "#fecdd3", "#f26b7f", "#fecdd3", "#ffe4e6"),
    ("lime", "Lime", "#4d7c0f", "#0d9488", "#d9f99d", "#86b52a", "#d9f99d", "#ecfccb"),
]

PALS = []   # (key, label, c1, c2, c3, tone)
for f in FAMILIES:
    k, n = f[0], f[1]
    PALS.append((f"{k}-rich", n, f[2], f[3], f[4], "rich"))
    PALS.append((f"{k}-soft", n, f[5], f[6], f[7], "soft"))
KEYS = tuple(p[0] for p in PALS)


def _mix(a, pct, b):
    return f"color-mix(in srgb,{a} {pct}%,{b})"


def build_css():
    out = []
    for key, label, c1, c2, c3, tone in PALS:
        soft = tone == "soft"
        L = [f"--p1:{c1}", f"--p2:{c2}", f"--p3:{c3}", f"--pri:{c1}", f"--pri-d:{_mix(c1, 78, '#000')}", f"--sec:{c2}", f"--sec-d:{_mix(c2, 78, '#000')}", f"--accent:{c3}",
             f"--pri2:{_mix(c1, 16 if soft else 10, '#fff')}", f"--pri3:{_mix(c1, 30 if soft else 24, '#fff')}",
             f"--bg:{_mix(c2, 16, '#fff') if soft else _mix(c1, 4, '#fff')}", f"--bg2:{_mix(c3, 38, '#fff') if soft else _mix(c2, 9, '#fff')}",
             f"--line:{_mix(c1, 30 if soft else 18, '#fff')}", f"--ink:{_mix(c1, 14, '#15121f')}", f"--mut:{_mix(c1, 18, '#5a5470')}", "--on:#fff"]
        if soft:    # pastel hues: keep white button text readable and headlines legible
            L += [f"--bt1:{_mix(c1, 64, '#000')}", f"--bt2:{_mix(_mix(c1, 50, c2), 62, '#000')}", f"--h1:{_mix(c1, 72, '#000')}", f"--h2:{_mix(_mix(c1, 50, c2), 66, '#000')}", f"--h3:{_mix(c3, 60, '#000')}"]
        out.append(f"html[data-pal={key}]{{{';'.join(L)}}}")
        d1, d2 = (_mix(c1, 88, '#fff'), _mix(c2, 88, '#fff')) if soft else (_mix(c1, 52, '#fff'), _mix(c2, 52, '#fff'))
        base, card = ("#12101d", "#1b1830") if soft else ("#08070d", "#13111b")
        D = [f"--p1:{d1}", f"--p2:{d2}", f"--p3:{c3}", f"--pri:{d1}", f"--pri-d:{_mix(d1, 50, '#fff')}", f"--sec:{d2}", f"--sec-d:{_mix(d2, 50, '#fff')}", f"--accent:{c3}",
             f"--bg:{_mix(c1, 12 if soft else 9, base)}", f"--bg2:{_mix(c2, 14 if soft else 11, base)}", f"--card:{_mix(c1, 10 if soft else 8, card)}",
             f"--pri2:{_mix(d1, 18, card)}", f"--pri3:{_mix(d1, 32, card)}", f"--line:{_mix(d1, 28, card)}", "--ink:#f4f1fb", f"--mut:{_mix(d1, 30, '#b5afc9')}"]
        out.append(f"html[data-theme=dark][data-pal={key}]{{{';'.join(D)}}}")
    return "\n".join(out)


START, END = "/* ===== vibes: generated by palettes.build_css() ===== */", "/* ===== end vibes ===== */"


def write_css(path="static/pop.css"):
    s = open(path).read()
    block = START + "\n" + build_css() + "\n" + END
    if START in s:
        s = s[:s.index(START)] + block + s[s.index(END) + len(END):]
    else:
        i = s.index("html[data-pal=citrus]")
        j = s.index("\n", s.index("html[data-theme=dark][data-pal=citrus]")) + 1
        s = s[:j] + block + "\n" + s[j:]
    open(path, "w").write(s)


if __name__ == "__main__":
    write_css()
